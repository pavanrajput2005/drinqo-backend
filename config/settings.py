# Google ID-token audiences are public OAuth client identifiers, not secrets.
# Invalid or missing configuration disables Google sign-in without preventing
# unrelated Django authentication routes from starting.
_GOOGLE_CLIENT_ID_PATTERN = re.compile(
    r"[0-9]+-[A-Za-z0-9_-]+\.apps\.googleusercontent\.com\Z"
)
_GOOGLE_CLIENT_IDS_RAW = os.getenv("GOOGLE_OAUTH_CLIENT_IDS", "")
_GOOGLE_CLIENT_IDS_PARTS = [
    client_id.strip() for client_id in _GOOGLE_CLIENT_IDS_RAW.split(",")
]
GOOGLE_OAUTH_CLIENT_IDS_CONFIG_VALID = bool(_GOOGLE_CLIENT_IDS_RAW.strip()) and all(
    _GOOGLE_CLIENT_ID_PATTERN.fullmatch(client_id)
    for client_id in _GOOGLE_CLIENT_IDS_PARTS
)
GOOGLE_OAUTH_CLIENT_IDS = tuple(
    dict.fromkeys(
        client_id
        for client_id in _GOOGLE_CLIENT_IDS_PARTS
        if client_id
    )
)

